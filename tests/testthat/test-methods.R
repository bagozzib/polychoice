test_that("imnl() recovers the parameters and nests the MNL at the boundary", {
  skip_on_cran()
  set.seed(3)
  di <- rmnl(4000, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)), delta = c(0.5, 1.2), inflate = "a")
  mi <- imnl(y ~ x1 + x2 | z1, data = di, inflate = "a")
  expect_true(mi$converged); expect_false(mi$boundary)
  truth <- c(0.5, -1, 0.8, -0.3, 0.6, -0.5, 0.5, 1.2)
  z <- (coef(mi) - truth) / sqrt(diag(vcov(mi)))
  expect_lt(max(abs(z)), 3.5)
  expect_equal(max(mi$start_logliks), mi$loglik, tolerance = 1e-8)
  ## a different base and the probit split run; inflate = a non-base alternative runs
  expect_equal(imnl(y ~ x1 + x2 | z1, data = di, ref = "b", inflate = "a")$loglik, mi$loglik, tolerance = 1e-6)
  mp <- imnl(y ~ x1 + x2 | z1, data = di, inflate = "a", link = "probit"); expect_true(mp$converged)
  mb <- imnl(y ~ x1 + x2 | z1, data = di, inflate = "b"); expect_s3_class(mb, "imnl")
  ## MNL data: the inflated fit cannot do worse than the MNL it nests at the boundary,
  ## and gains little (a mixture absorbs some noise; it may or may not reach the boundary)
  d0 <- rmnl(1500, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)))
  d0$z1 <- rnorm(nrow(d0))
  m0i <- suppressWarnings(imnl(y ~ x1 + x2 | z1, data = d0, inflate = "a"))
  l0 <- mnl(y ~ x1 + x2, data = d0)$loglik
  expect_gte(m0i$loglik, l0 - 1e-6); expect_lt(m0i$loglik - l0, 5)
})

test_that("vuong() and lr_test() match hand computations and refuse improper pairs", {
  skip_on_cran()                                    # slow; runs in the full suite (check time, 2026-11-06)
  set.seed(2)
  d <- rmnl(1500, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)), delta = c(0.5, 1.2), inflate = "a")
  mi <- imnl(y ~ x1 + x2 | z1, data = d, inflate = "a"); m0 <- mnl(y ~ x1 + x2, data = d)
  v <- vuong(mi, m0)
  mdiff <- mi$lli - m0$lli
  expect_equal(v$statistic[v$correction == "raw"], sqrt(length(mdiff)) * mean(mdiff) / sqrt(mean((mdiff - mean(mdiff))^2)), tolerance = 1e-8)
  expect_equal(v$statistic[v$correction == "AIC"], (sum(mdiff) - (mi$df - m0$df)) / (sqrt(length(mdiff)) * sqrt(mean((mdiff - mean(mdiff))^2))), tolerance = 1e-8)
  expect_gt(v$statistic[1], 2)
  expect_error(lr_test(m0, mi), "boundary")
  m1 <- mnl(y ~ x1, data = d)
  lr <- lr_test(m1, m0)
  expect_equal(lr$statistic, 2 * (m0$loglik - m1$loglik)); expect_equal(lr$df, 2L)
  expect_error(lr_test(m0, m1), "more parameters|not nested")
  expect_error(vuong(m0, mnl(y ~ x1, data = d[-1, ])), "same cases")
  cm <- compare_models(mi, m0)
  expect_equal(cm$model, c("mi", "m0")); expect_equal(cm$df, c(8L, 6L))
})

test_that("fit_stats() and classification() are consistent and weight-aware", {
  set.seed(4)
  d <- rmnl(900, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)))
  m <- mnl(y ~ x1 + x2, data = d)
  fs <- fit_stats(m)
  m0 <- mnl(y ~ 1, data = d)
  expect_equal(fs$loglik_null, m0$loglik, tolerance = 1e-8)
  expect_equal(fs$mcfadden, 1 - m$loglik / m0$loglik, tolerance = 1e-10)
  cl <- classification(m)
  expect_equal(unname(cl$correct), unname(fs$count), tolerance = 1e-12)
  expect_equal(sum(cl$table), nrow(d))
  expect_equal(unname(cl$pre), unname(fs$count_adj), tolerance = 1e-12)
  ## the null for a model without constants is the equiprobable choice
  mn <- mnl(y ~ 0 + x1, data = d)
  expect_equal(fit_stats(mn)$loglik_null, nrow(d) * log(1 / 3), tolerance = 1e-10)
})

test_that("first_difference() agrees with direct predictions and supports every option", {
  skip_on_cran()                                    # slow; runs in the full suite (check time, 2026-11-06)
  set.seed(5)
  d <- rmnl(1200, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)), delta = c(0.5, 1.2), inflate = "a")
  d$g <- factor(sample(c("u", "v", "w"), nrow(d), TRUE))
  m <- mnl(y ~ x1 + x2 + g, data = d)
  fd <- first_difference(m, "x1", 0, 1)
  prof <- .pc_profile(m); p0 <- predict(m, newdata = .pc_set_var(prof, "x1", 0)); p1 <- predict(m, newdata = .pc_set_var(prof, "x1", 1))
  expect_equal(fd$diff, unname(as.vector(p1 - p0)), tolerance = 1e-10)
  expect_equal(fd$alternative, c("a", "b", "c"))
  expect_true(all(fd$lower < fd$diff & fd$diff < fd$upper))
  fda <- first_difference(m, "x1", 0, 1, average = TRUE)
  d0 <- d; d0$x1 <- 0; d1 <- d; d1$x1 <- 1
  expect_equal(fda$diff, unname(colMeans(predict(m, newdata = d1)) - colMeans(predict(m, newdata = d0))), tolerance = 1e-10)
  fdg <- first_difference(m, "g", "u", "w", ci = "sim", R = 200)
  expect_equal(nrow(fdg), 3L); expect_true(all(is.finite(fdg$lower)))
  expect_error(first_difference(m, "g", "u", "zzz"), "not a level")
  mi <- imnl(y ~ x1 + x2 | z1 + x1, data = d, inflate = "a")
  fo <- first_difference(mi, "x1", 0, 1, type = "prob_outcome")
  fr <- first_difference(mi, "x1", 0, 1, type = "regime"); expect_equal(nrow(fr), 1L)
  fs <- first_difference(mi, "x1", 0, 1, stage = "inflation")
  fo2 <- first_difference(mi, "x1", 0, 1, stage = "outcome", type = "prob_outcome")
  expect_equal(fo$diff, fo2$diff, tolerance = 1e-10)                # the outcome-stage probabilities ignore the inflation stage
  expect_error(first_difference(m, "x1", 0, 1, type = "regime"), "inflated models only")
  expect_equal(sum(fd$diff), 0, tolerance = 1e-10)
  rr <- rrr(m)
  expect_equal(rr$rrr, unname(exp(coef(m))), tolerance = 1e-12)
  expect_equal(nrow(rrr(mi)), length(coef(mi)))
})

test_that("mundlak(), update(), simulate(), residuals(), and the bootstrap work", {
  skip_on_cran()                                    # slow; runs in the full suite (check time, 2026-11-06)
  set.seed(6)
  d <- rmnl(900, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)), delta = c(0.5, 1.2), inflate = "a")
  d$unit <- rep(1:30, each = 30)
  md <- mundlak(y ~ x1 + x2 | z1, d, unit = "unit")
  expect_equal(md$added, c("x1_mean", "x2_mean", "z1_mean"))
  expect_equal(length(Formula::Formula(md$formula))[2], 2L)
  mm <- imnl(md$formula, md$data, inflate = "a", cluster = "unit")
  expect_true(all(c("b:x1_mean", "infl_z1_mean") %in% names(coef(mm))))
  m <- mnl(y ~ x1 + x2, data = d)
  m2 <- update(m, . ~ . - x2); expect_equal(m2$df, 4L)
  mi <- imnl(y ~ x1 + x2 | z1 + x1, data = d, inflate = "a")
  mi2 <- update(mi, . ~ . | . - x1); expect_equal(mi2$df, mi$df - 1L)
  s <- simulate(mi, nsim = 2, seed = 1)
  expect_equal(dim(s), c(nrow(d), 2L)); expect_equal(levels(s$sim_1), mi$levels)
  R <- residuals(m); expect_equal(dim(R), c(nrow(d), 3L)); expect_equal(unname(rowSums(R)), rep(0, nrow(d)), tolerance = 1e-12)
  expect_equal(AIC(m), -2 * m$loglik + 2 * m$df); expect_equal(nobs(m), nrow(d))
  skip_on_cran()
  set.seed(1)
  mb <- mnl(y ~ x1 + x2, data = d, se = "bootstrap", nboot = 40)
  expect_equal(dim(mb$boot$replicates), c(40L, 6L))
  expect_equal(unname(sqrt(diag(vcov(mb)))), unname(sqrt(diag(vcov(m)))), tolerance = 0.5)
  ci <- confint(mb, type = "percentile"); expect_equal(dim(ci), c(6L, 2L))
  expect_error(confint(m, type = "percentile"), "bootstrap")
})

test_that("broom and texreg integration", {
  skip_if_not_installed("broom")
  set.seed(7)
  d <- rmnl(500, beta = cbind(b = c(0.5, -1, 0.8), c = c(-0.3, 0.6, -0.5)), delta = c(0.5, 1), inflate = "a")
  mi <- imnl(y ~ x1 + x2 | z1, data = d, inflate = "a")
  td <- broom::tidy(mi, conf.int = TRUE)
  expect_equal(nrow(td), 8L); expect_true(all(c("component", "conf.low") %in% names(td)))
  expect_equal(td$component, c(rep("outcome", 6), rep("inflation", 2)))
  g <- broom::glance(mi); expect_equal(g$inflate, "a"); expect_true(g$converged)
  a <- broom::augment(mi); expect_equal(nrow(a), 500L); expect_true(".regime" %in% names(a))
  skip_if_not_installed("texreg")
  tr <- texreg::extract(mi)
  expect_equal(length(tr@coef), 8L); expect_true("Share in inflated alt." %in% tr@gof.names)
})
